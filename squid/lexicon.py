"""
TDL lexicon generation from database schemas.

Generates ERG-compatible TDL lexical entries for domain vocabulary
(table names, column names) to solve the unknown word problem.
"""

from __future__ import annotations

import re
import tempfile
from pathlib import Path
from typing import List, Set

from squid.schema import Schema

# Common English words that are already in the ERG lexicon
# This is a simplified stopword list; ideally we'd check against the actual ERG lexicon
KNOWN_WORDS: Set[str] = {
    'id', 'name', 'type', 'date', 'time', 'year', 'month', 'day',
    'number', 'count', 'amount', 'total', 'value', 'price', 'cost',
    'description', 'status', 'code', 'email', 'phone', 'address',
    'city', 'state', 'country', 'zip', 'postal',
    'first', 'last', 'middle', 'full',
    'active', 'deleted', 'created', 'updated', 'modified',
    'start', 'end', 'begin', 'finish',
    'user', 'customer', 'person', 'people', 'member',
}


def split_identifier(identifier: str) -> List[str]:
    """
    Split a database identifier into words.

    Handles:
    - Underscores: student_id -> ['student', 'id']
    - CamelCase: StudentName -> ['student', 'name']
    - Numbers: student2 -> ['student', '2'] (filtered out later)

    Args:
        identifier: Database table or column name

    Returns:
        List of words
    """
    # Replace underscores with spaces
    identifier = identifier.replace('_', ' ')

    # Split camelCase: insert space before uppercase letters
    identifier = re.sub(r'([a-z])([A-Z])', r'\1 \2', identifier)

    # Split on spaces and convert to lowercase
    words = [w.lower().strip() for w in identifier.split()]

    # Filter out empty strings and numbers
    words = [w for w in words if w and not w.isdigit()]

    return words


def sanitize_for_tdl(word: str) -> str:
    """
    Sanitize a word for use in TDL format.

    TDL identifiers must be lowercase and contain only letters, digits, underscores, and hyphens.

    Args:
        word: Raw word

    Returns:
        Sanitized word suitable for TDL
    """
    # Convert to lowercase
    word = word.lower()

    # Replace invalid characters with underscores
    word = re.sub(r'[^a-z0-9_-]', '_', word)

    # Remove leading/trailing underscores
    word = word.strip('_')

    return word


def should_include_word(word: str) -> bool:
    """
    Check if a word should be included in the TDL lexicon.

    Excludes:
    - Words already in the ERG lexicon (common words)
    - Very short words (1-2 characters, usually abbreviations)
    - Words with only digits

    Args:
        word: Word to check

    Returns:
        True if word should be included
    """
    if not word or len(word) <= 2:
        return False

    if word in KNOWN_WORDS:
        return False

    if word.isdigit():
        return False

    return True


def make_tdl_entry(word: str, pos: str = 'noun') -> str:
    """
    Generate a TDL lexical entry for a word.

    Args:
        word: The word (sanitized)
        pos: Part of speech: 'noun', 'adj', or 'mass'

    Returns:
        TDL entry string
    """
    # Map POS to ERG lexical types
    if pos == 'noun':
        lex_type = 'n_-_c_le'  # intransitive count noun
        pred_suffix = 'n_1'
    elif pos == 'adj':
        lex_type = 'aj_-_i_le'  # intransitive adjective
        pred_suffix = 'a_1'
    elif pos == 'mass':
        lex_type = 'n_-_m_le'  # mass noun
        pred_suffix = 'n_1'
    else:
        lex_type = 'n_-_c_le'
        pred_suffix = 'n_1'

    # Generate PRED value following ERG convention
    pred = f"_{word}_{pred_suffix}_rel"

    # Generate TDL entry
    entry = f"""{word} := {lex_type} &
  [ STEM < "{word}" >,
    SYNSEM.LKEYS.KEYREL.PRED "{pred}" ].
"""

    return entry


def generate_tdl(schema: Schema) -> str:
    """
    Generate TDL lexicon entries for all domain vocabulary in the schema.

    Args:
        schema: Database schema

    Returns:
        Complete TDL lexicon as string
    """
    entries: List[str] = []
    seen_words: Set[str] = set()

    # Header comment
    entries.append(f"""; TDL lexicon for {schema.db_id}
; Auto-generated by SQUID
; This lexicon provides domain-specific vocabulary for the ERG parser

""")

    # Process all tables
    for table in schema.tables:
        words = split_identifier(table.name)
        for word in words:
            word = sanitize_for_tdl(word)
            if should_include_word(word) and word not in seen_words:
                entries.append(make_tdl_entry(word, pos='noun'))
                seen_words.add(word)

        # Process all columns in this table
        for column in table.columns:
            words = split_identifier(column.name)
            for word in words:
                word = sanitize_for_tdl(word)
                if should_include_word(word) and word not in seen_words:
                    # Check if this looks like a boolean column (use adjective)
                    if word in ('active', 'enabled', 'deleted', 'archived', 'verified',
                                'confirmed', 'approved', 'completed', 'finished', 'closed'):
                        entries.append(make_tdl_entry(word, pos='adj'))
                    # Check if this looks like a mass noun
                    elif word in ('data', 'information', 'software', 'equipment',
                                  'furniture', 'luggage', 'mail'):
                        entries.append(make_tdl_entry(word, pos='mass'))
                    else:
                        entries.append(make_tdl_entry(word, pos='noun'))
                    seen_words.add(word)

    return ''.join(entries)


def write_tdl(schema: Schema, output_path: str | None = None) -> Path:
    """
    Write the TDL lexicon file to disk for ACE to load.

    Args:
        schema: Database schema
        output_path: Optional output path; if None, creates a temp file

    Returns:
        Path to the written TDL file
    """
    tdl_content = generate_tdl(schema)

    if output_path is None:
        # Create temporary file
        fd, output_path = tempfile.mkstemp(suffix='.tdl', prefix=f'squid_{schema.db_id}_')
        with open(fd, 'w', encoding='utf-8') as f:
            f.write(tdl_content)
    else:
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(tdl_content)

    return Path(output_path)
